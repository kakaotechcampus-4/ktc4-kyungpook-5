"""AI 모듈이 BE에 올리는 오류 타입을 정의한다.

AI 처리에 실패했을 때 빈 결과를 반환하지 않고 예외로 전달한다.
BE는 예외 타입을 보고 사용자에게 재시도를 안내할지,
서버 오류로 처리할지 결정한다.

HTTP 상태 코드나 API 응답 코드로 변환하는 책임은 BE에 있다.
이 파일에서는 BE가 실패 원인을 구분하는 데 필요한 예외 타입만 정의한다.

    AIError
    ├── AIConfigError       설정 오류 - 다시 시도해도 같은 문제가 발생한다
    └── AIRetryableError    같은 요청을 다시 시도하면 성공할 수 있다
        ├── AITimeoutError
        └── AIInvalidResponseError

예상하지 못한 예외는 AIError로 변환X
-> 이런 예외는 그대로 BE에 전달해 서버 오류로 처리한다.
"""


class AIError(Exception):
    """AI 모듈에서 발생한 오류의 최상위 타입."""


class AIConfigError(AIError):
    """AI 실행에 필요한 설정이 없거나 잘못된 경우.

    예:
    - API 주소가 잘못된 경우
    - API 키가 없거나 유효하지 않은 경우
    - 모델 이름이 잘못된 경우

    설정을 수정하기 전에는 같은 요청을 다시 보내도 실패하므로
    사용자에게 재시도를 권하지 않는다
    """


class AIRetryableError(AIError):
    """같은 요청을 다시 시도하면 성공할 수 있는 오류.

    `llm.py`에서 일시적인 오류에 대해 최대 DEFAULT_MAX_RETRIES만큼
    내부 재시도를 수행한 뒤에도 실패하면 이 계열의 예외가 전달된다.

    계획 생성이나 답변 생성처럼 결과만 만드는 작업은 다시 요청할 수 있다.
    반면 송금·메시지 전송처럼 외부 상태를 변경하는 작업의 재실행 여부는
    AI가 결정하지 않고 BE가 실행 상태를 확인한 뒤 판단한다.
    """


class AITimeoutError(AIRetryableError):
    """모델 응답을 제한 시간 안에 받지 못한 경우.

    모델 호출이 오래 걸려 제한 시간을 초과했을 때 사용한다.
    BE가 일반적인 재시도 오류와 구분해 안내하거나 처리할 수 있도록
    별도의 타입으로 정의한다.

    타임아웃이 발생해도 모델 쪽 처리가 완료되었을 가능성이 있으므로
    작업이 실행되지 않았다고 단정하지 않는다.
    """


class AIInvalidResponseError(AIRetryableError):
    """모델 응답이 기대한 데이터 형식을 만족하지 않은 경우.

    구조화 출력이 예상한 형식과 다르거나
    `contracts.py`의 데이터 검증을 통과하지 못했을 때 사용한다.

    누락되거나 잘못된 값을 임의의 기본값으로 채워 정상 결과처럼 반환하지 않는다

    같은 입력이라도 다시 생성하면 정상적인 응답이 나올 수 있으므로
    재시도 가능한 오류로 분류한다.
    """
